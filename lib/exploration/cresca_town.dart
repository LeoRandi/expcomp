bool _townRoad(int x, int y) =>
    ((y == 26 || y == 27) && x >= 0 && x <= 54) ||
    (y == 25 && const [13, 20, 27, 34, 41].contains(x)) ||
    ((x == 29 || x == 30) && y >= 0 && y <= 54) ||
    (y == 32 && x >= 12 && x <= 42) ||
    (const [12, 19, 31, 38].contains(x) && y >= 27 && y <= 32);
